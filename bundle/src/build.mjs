import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { resolve, join } from 'node:path';
import { createHash } from 'node:crypto';
import { ROLES, presetDeclarations, emitYaml } from './presets.mjs';
import { SKILL_ROUTING, OPTIONAL_ROLES, renderSkillRouting } from './skill-routing.mjs';

export async function buildBundle(root, { check = false } = {}) {
  const prompts = {};
  const sources = {};
  const shared = (await readFile(join(root, 'prompts', 'shared.md'), 'utf8')).replace(/\r\n/g, '\n').trim();
  if (!shared) throw new Error('prompts/shared.md is empty');
  sources['prompts/shared.md'] = createHash('sha256').update(shared).digest('hex');
  for (const role of ROLES) {
    const relativePath = `prompts/${role.id}.md`;
    const text = (await readFile(join(root, relativePath), 'utf8')).replace(/\r\n/g, '\n').trim();
    if (!text) throw new Error(`${relativePath} is empty`);
    prompts[role.id] = `${shared}\n\n${text}\n\n${renderSkillRouting(role.id)}`;
    sources[relativePath] = createHash('sha256').update(text).digest('hex');
  }
  const files = {
    'cordis.patch.yml': `# Generated by node src/build.mjs. Edit prompts/*.md or src/presets.mjs, then rebuild.\n${emitYaml(presetDeclarations(prompts))}\n`,
    'provenance.json': `${JSON.stringify({
      schema_version: 1, bundle_version: SKILL_ROUTING.bundle_version, target_runtime: '0.2.1-rc.2', ptc: 'Programmatic Tool Calling',
      role_count: ROLES.length, optional_roles: OPTIONAL_ROLES,
      base: 'Installed dsh-web-app/presets/ptc.patch.yml, read from E:/dsh desktop/resources/app.asar on 2026-10-24',
      omissions: ['schedule and goal automation', 'fork delegation', 'workflow and Ralph', 'plugin management'],
      modifications: ['12 role personas retaining the original 11 IDs', 'optional code lead off by default at task policy level', 'native spawn preset allowlists and readback preflight', 'explicit maxDepth=2', '.mcm-project root marker', 'captain-only audit tool', 'task-specific skill routing without invented SDK permission fields', 'lightweight context packs, dynamic capacity, visual evidence and user paper framework', 'skill-filesystem watch=false; external skill changes require verified session refresh, not assumed hot reload'],
      assurance: 'Role/tool declarations are not an OS sandbox; inherited or global tools require runtime inspection. Optional role activation and skill routing are task policies, not Host-enforced permissions.',
      skill_routing_sha256: createHash('sha256').update(JSON.stringify(SKILL_ROUTING)).digest('hex'),
      routing_source_sha256: createHash('sha256').update(await readFile(new URL('./skill-routing.mjs', import.meta.url))).digest('hex'),
      runtime_guard_source_sha256: Object.fromEntries(await Promise.all(['runtime-guard-core.mjs','runtime-guard-plugin.mjs'].map(async name=>[`src/${name}`,createHash('sha256').update(await readFile(new URL(`./${name}`,import.meta.url))).digest('hex')]))),
      prompt_sha256: sources
    }, null, 2)}\n`
  };
  for (const [name, content] of Object.entries(files)) {
    if (check) {
      let current;
      try { current = await readFile(join(root, name), 'utf8'); } catch { throw new Error(`${name} is missing; run npm run build`); }
      if (current !== content) throw new Error(`${name} is stale; run npm run build`);
    } else await writeFile(join(root, name), content, 'utf8');
  }
  return { role_count: ROLES.length, bundle_version: SKILL_ROUTING.bundle_version, optional_roles: OPTIONAL_ROLES, files: Object.keys(files), prompt_bytes: Object.fromEntries(Object.entries(prompts).map(([id, text]) => [id, Buffer.byteLength(text)])) };
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const root = fileURLToPath(new URL('../', import.meta.url));
  const result = await buildBundle(root, { check: process.argv.includes('--check') });
  console.log(`${process.argv.includes('--check') ? 'Verified' : 'Built'} ${result.role_count} role presets.`);
}
